#membership operators

#a) in operator in membership operator is used to check whether a value is present in a sequence or not. It returns True if the value is present, otherwise it returns False. 
a = [10,20,30,40,50]
print(20 in a)
s = "Sanjay"
print("j" in s)

# b) not in operator in membership operator is used to check whether a value is not present in a sequence or not. It returns True if the value is not present, otherwise it returns False.
print(100 not in a)
print("k" not in s)

numbers = [10,20,'7', 40, 50]
print(7 in numbers)
print(2 not in numbers)
